def has_regional_presence(item: dict[str, Any]) -> bool:
    """Check whether an event item mentions a Middle East country, city, or waterway."""
    countries = item.get("countries") or []
    location = item.get("location") or ""
    for c in countries:
        if is_middle_east_country(c):
            return True
    if mentions_middle_east_place(location):
        return True
    return False


def _format_source_display(source: str, url: str, as_html: bool = True) -> str:
    """Format source label with Google News note when origin is news.google.com."""
    clean_src = str(source or "منبع").strip()
    clean_url = str(url or "").strip()
    if "news.google.com" in clean_url:
        clean_src = f"{clean_src} (Google News)" if clean_src else "Google News"
    if as_html and clean_url:
        return f'<a href="{esc(clean_url)}">{esc(clean_src)}</a>'
    elif as_html:
        return esc(clean_src)
    elif clean_url:
        return f"{clean_src}: {clean_url}"
    return clean_src


def _item_sort_key(it: dict[str, Any]) -> tuple[int, int, float]:
    """Sort key for daily bulletin: importance DESC, source count DESC, recency DESC."""
    imp = int(it.get("importance") or 3)
    srcs = int(it.get("total_sources_count") or len(it.get("additional_sources") or []) + 1)
    ts = 0.0
    fs = it.get("first_seen_at")
    if fs:
        try:
            ts = datetime.fromisoformat(fs).timestamp()
        except Exception:
            pass
    return (imp, srcs, ts)



def _utcnow() -> datetime:
    return datetime.now(UTC)


def report_created_after_cutoff() -> datetime | None:
    """Earliest ``Event.created_at`` admitted into the bulletin (Phase R-5).

    Only events ingested after the language and verification guards went live are
    worth publishing; an empty ``daily_report_min_created_at`` disables the filter.
    """
    raw = (settings.daily_report_min_created_at or "").strip()
    if not raw:
        return None
    try:
        cutoff_date = date.fromisoformat(raw)
    except ValueError:
        logger.warning(
            "Invalid daily_report_min_created_at=%r; the created_at filter stays disabled.",
            raw,
        )
        return None
    return datetime.combine(cutoff_date, time.min, tzinfo=UTC)


def _resolved_verification_status(model_status: str, source_count: int) -> str:
    """Re-derive the verification label from corroboration at render time (R-1).

    ``app.processors.pipeline`` owns this rule but reaches this module through the
    Telegram publisher, so the import stays local to avoid a cycle.
    """
    from app.processors.pipeline import resolve_verification_status

    return resolve_verification_status(model_status, source_count)


def is_summary_mock(summary: Summary | Any) -> bool:
    """Detect whether a summary was generated by a mock provider or test placeholder."""
    model_name = getattr(summary, "model_name", "") or ""
    prompt_ver = getattr(summary, "prompt_version", "") or ""
    headline = getattr(summary, "headline_fa", "") or ""
    text = getattr(summary, "summary_fa", "") or ""

    if str(model_name).lower() in ("mock", "mockaiprovider", "test", "none"):
        return True
    if str(prompt_ver).lower() in ("mock", "test"):
        return True
    if headline.startswith("تیتر خبر") or text.startswith("خلاصه خبر"):
        return True
    if headline in ("رایزنی‌های دیپلماتیک منطقه‌ای", "Regional Diplomatic Activity"):
        return True
    return False


def report_slot_hours() -> tuple[int, ...]:
    """Configured briefing hours in local time, sorted and de-duplicated."""
    hours: list[int] = []
    for raw in (settings.report_slots or "").split(","):
        value = raw.strip()
        if value.isdigit() and 0 <= int(value) <= 23:
            hours.append(int(value))
    return tuple(sorted(set(hours))) or (settings.daily_report_hour,)


def slot_label(slot_hour: int) -> str:
    """Stable key for one briefing slot, e.g. ``"14:00"``."""
    return f"{slot_hour:02d}:00"


def current_slot_hour(now: datetime | None = None) -> int:
    """The briefing slot that is due now: the latest configured hour already passed."""
    tz = ZoneInfo(settings.timezone)
    moment = now or datetime.now(tz)
    slots = report_slot_hours()
    due = [hour for hour in slots if hour <= moment.hour]
    return due[-1] if due else slots[-1]


def latest_slot_start(now: datetime, slot_hour: int) -> datetime:
    """The most recent start of ``slot_hour`` at or before ``now`` (Phase Y-10).

    A run that catches up at 00:42 for the 20:00 slot belongs to *yesterday's* slot:
    its window is 08:00-20:00 of the previous day, and its report_date must say so.
    """
    start = now.replace(hour=slot_hour, minute=0, second=0, microsecond=0)
    if start > now:
        start -= timedelta(days=1)
    return start


def slot_report_date(slot_hour: int, now: datetime | None = None) -> date:
    """The report date a briefing slot belongs to, using the most recent start."""
    tz = ZoneInfo(settings.timezone)
    moment = now or datetime.now(tz)
    return latest_slot_start(moment, slot_hour).date()


def slot_start(report_date: date, slot_hour: int) -> datetime:
    """The exact local start of one briefing slot."""
    tz = ZoneInfo(settings.timezone)
    return datetime.combine(report_date, time(hour=slot_hour, minute=0), tzinfo=tz)


def current_due_slot(now: datetime | None = None) -> tuple[date, int] | None:
    """The slot that is due right now, i.e. started within ``slot_grace_hours``.

    Returns ``(report_date, slot_hour)`` or ``None`` when no slot is currently inside
    its catch-up window. The report date is the day the slot started, so a 00:42 run
    still belongs to yesterday's 20:00 slot.
    """
    tz = ZoneInfo(settings.timezone)
    moment = (now or datetime.now(tz)).astimezone(tz)
    grace_hours = min(max(1, settings.slot_grace_hours), 11)
    for day_offset in (0, 1):
        day = moment.date() - timedelta(days=day_offset)
        for hour in sorted(report_slot_hours(), reverse=True):
            start = slot_start(day, hour)
            if start <= moment and moment - start < timedelta(hours=grace_hours):
                return day, hour
    return None


def slot_candidates(
    now: datetime | None = None,
    lookback_hours: int | None = None,
) -> list[tuple[date, int]]:
    """All slot starts inside the recovery lookback, oldest first.

    A dropped scheduled run leaves a slot with no publication record; walking every
    configured slot start (rather than only the one that is due) is what lets the next
    run recover the ones it missed.
    """
    tz = ZoneInfo(settings.timezone)
    moment = (now or datetime.now(tz)).astimezone(tz)
    lookback = lookback_hours if lookback_hours is not None else settings.slot_recovery_lookback_hours
    lookback = max(0, int(lookback))
    out: list[tuple[date, int]] = []
    horizon = timedelta(hours=lookback)
    for day_offset in range(0, lookback // 24 + 2):
        day = moment.date() - timedelta(days=day_offset)
        for hour in report_slot_hours():
            start = slot_start(day, hour)
            if start <= moment and moment - start <= horizon:
                out.append((day, hour))
    return sorted(out, key=lambda candidate: slot_start(*candidate))


def report_window(
    report_date: date | None = None,
    slot_hour: int | None = None,
) -> tuple[date, datetime, datetime]:
    """Return (report_date, window_start, window_end).

    Without a slot this is the original 24-hour window anchored at the configured
    daily-report time, so repeated or delayed runs stay idempotent. With a slot it
    ends at that hour and starts at the previous slot, which keeps the three daily
    briefings gapless and free of overlap.
    """
    tz = ZoneInfo(settings.timezone)
    if report_date is None:
        # Phase Y-10: without an explicit date, a slot's window belongs to the day
        # the slot actually started, not to the calendar day of this late run.
        report_date = (
            slot_report_date(slot_hour) if slot_hour is not None else datetime.now(tz).date()
        )

    if slot_hour is None:
        end_hour = settings.daily_report_hour
        end_minute = settings.daily_report_minute
        window_hours = 24
    else:
        slots = report_slot_hours()
        earlier = [hour for hour in slots if hour < slot_hour]
        previous_hour = earlier[-1] if earlier else slots[-1]
        end_hour, end_minute = slot_hour, 0
        window_hours = (slot_hour - previous_hour) % 24 or 24

    window_end = datetime.combine(
        report_date,
        time(hour=end_hour, minute=end_minute),
        tzinfo=tz,
    )
    window_start = window_end - timedelta(hours=window_hours)
    return report_date, window_start, window_end


async def _log_empty_window(
    session: AsyncSession,
    window_start: datetime,
    window_end: datetime,
    min_importance: int,
) -> None:
    """Explain an empty briefing instead of guessing why nothing was eligible.

    Without this, an empty bulletin is indistinguishable from a genuinely quiet
    window: an empty result could mean no events, an importance cut, a missing
    summary, or a window that does not contain the events the pipeline just wrote.
    """
    try:
        in_window = select(func.count(Event.id)).where(
            Event.first_seen_at >= window_start, Event.first_seen_at < window_end
        )
        with_summary = (
            select(func.count(Event.id))
            .join(Summary, Summary.event_id == Event.id)
            .where(Event.first_seen_at >= window_start, Event.first_seen_at < window_end)
        )
        # Measured with scalar() calls so the diagnostic never disturbs the report
        # query itself or the statement order callers rely on.
        total = await session.scalar(in_window)
        summarised = await session.scalar(with_summary)
        earliest = await session.scalar(select(func.min(Event.first_seen_at)))
        latest = await session.scalar(select(func.max(Event.first_seen_at)))
        logger.warning(
            "No eligible events for window %s .. %s (min_importance=%d): "
            "%s event(s) in window, %s with a summary; stored events span %s .. %s.",
            window_start.isoformat(),
            window_end.isoformat(),
            min_importance,
            total,
            summarised,
            earliest.isoformat() if earliest else None,
            latest.isoformat() if latest else None,
        )
    except Exception:
        logger.exception("Could not describe an empty report window")


async def fetch_report_items(
    session: AsyncSession,
    report_date: date | None = None,
    min_importance: int | None = None,
    slot_hour: int | None = None,
    include_all: bool = False,
) -> tuple[date, list[dict[str, Any]], dict[str, Any]]:
    """Query PostgreSQL for events in the report window matching report criteria.

    Strictly excludes any events containing articles with status 'flagged_for_review' or 'rejected'.
    Collects primary and supplementary source citations (Staleness Policy Option C).

    ``include_all`` is the completeness mode used by the Telegraph report: membership is
    decided only by the article collection time inside the half-open window, with no
    importance threshold, no regional filter, no item cap and no exclusion of events
    parked for review. ``flagged_events_included`` and ``review_pending`` keep that state
    visible instead of hiding it. Stories whose analysis produced no summary are added by
    :func:`app.reports.telegraph_report.fetch_complete_window_items`.
    """
    if min_importance is None:
        min_importance = settings.min_importance

    report_date, window_start, window_end = report_window(report_date, slot_hour)

    # Subquery: identify events that have ANY article with flagged_for_review or rejected status
    flagged_subquery = (
        select(ArticleEvent.event_id)
        .join(Article, Article.id == ArticleEvent.article_id)
        .where(Article.status.in_(["flagged_for_review", "rejected"]))
    )

    # Membership is decided by the collection time of the linked articles, in the half-open
    # window. A story therefore belongs to exactly one report even when its summary is
    # produced hours later, and a story already published yesterday is never dropped from
    # today's report for that reason alone.
    collected_in_window = (
        select(ArticleEvent.event_id)
        .join(Article, Article.id == ArticleEvent.article_id)
        .where(
            Article.collected_at >= window_start,
            Article.collected_at < window_end,
        )
    )
    conditions = [Event.id.in_(collected_in_window)]
    flagged_events_included = 0
    flagged_ids: set[int] = set()
    if include_all:
        # A parked event is still collected news: it is published and marked, not dropped.
        flagged_rows = await session.scalars(
            select(ArticleEvent.event_id)
            .join(Article, Article.id == ArticleEvent.article_id)
            .where(Article.status.in_(["flagged_for_review", "rejected"]))
            .distinct()
        )
        flagged_ids = {int(event_id) for event_id in flagged_rows.all()}
        flagged_events_included = len(flagged_ids)
        if flagged_events_included:
            logger.warning(
                "%d event(s) in this window are parked for review; they are published with "
                "a review marker rather than silently removed.",
                flagged_events_included,
            )
    else:
        conditions.append(Event.id.not_in(flagged_subquery))
        conditions.append(Event.importance >= min_importance)
        created_after = report_created_after_cutoff()
        if created_after is not None:
            # ``events`` has no created_at column (and adding one would need a migration);
            # first_seen_at is its ingestion timestamp, set once when the event is inserted.
            conditions.append(Event.first_seen_at >= created_after)

    # Query events in time window with importance threshold, excluding flagged
    stmt = (
        select(Event, Summary)
        .join(Summary, Summary.event_id == Event.id)
        .where(*conditions)
        .order_by(Event.importance.desc(), Event.first_seen_at.desc())
    )

    event_summary_rows = (await session.execute(stmt)).all()
    if not event_summary_rows:
        await _log_empty_window(session, window_start, window_end, min_importance)
        metadata = {
            "report_date": str(report_date),
            "generated_at": _utcnow().isoformat(),
            "min_importance": min_importance,
            "total_events": 0,
            "strategic_events_count": 0,
            "regional_events_count": 0,
            "events_before_cap": 0,
            "max_items": settings.max_daily_report_items,
            "language_rejected_count": 0,
            "min_created_at": (settings.daily_report_min_created_at or "").strip() or None,
            "completeness": "all_events" if include_all else "filtered",
            "flagged_events_included": flagged_events_included,
        }
        return report_date, [], metadata

    event_ids = [ev.id for ev, _ in event_summary_rows]

    # Fetch all linked articles and their sources for these events
    articles_stmt = (
        select(ArticleEvent.event_id, Article, Source)
        .join(Article, Article.id == ArticleEvent.article_id)
        .join(Source, Source.id == Article.source_id)
        .where(ArticleEvent.event_id.in_(event_ids))
        .order_by(ArticleEvent.confidence.desc().nullslast(), Article.collected_at.asc())
    )
    article_rows = (await session.execute(articles_stmt)).all()

    # Group articles by event_id
    articles_by_event: dict[int, list[tuple[Article, Source]]] = {eid: [] for eid in event_ids}
    for eid, art, src in article_rows:
        articles_by_event[eid].append((art, src))

    items: list[dict[str, Any]] = []
    seen_event_ids: set[int] = set()
    mock_count = 0
    real_count = 0
    language_rejected_count = 0

    for event, summary in event_summary_rows:
        if event.id in seen_event_ids:
            continue
        seen_event_ids.add(event.id)

        # R-1: stored text may predate the Phase N guard, so re-check it here. A filtered
        # bulletin drops it; the completeness report keeps it with an explicit warning
        # rather than losing a collected story.
        language_warning = False
        if not (
            passes_persian_guard(summary.headline_fa)
            and passes_persian_guard(summary.summary_fa)
        ):
            language_rejected_count += 1
            language_warning = True
            if not include_all:
                logger.warning(
                    "Event #%d dropped from the daily report: headline/summary failed the Persian language guard.",
                    event.id,
                )
                continue
            logger.warning(
                "Event #%d is included with a language warning: its summary failed the Persian guard.",
                event.id,
            )

        is_mock = is_summary_mock(summary)
        if is_mock:
            mock_count += 1
        else:
            real_count += 1

        linked_arts = articles_by_event.get(event.id, [])

        # R-1: independent sources are recounted from the linked articles at render
        # time, so a stale stored verdict can never present a single source as confirmed.
        distinct_sources = len(
            {
                art.source_id
                for art, _src in linked_arts
                if getattr(art, "source_id", None) is not None
            }
        )

        topic = topic_for_event(event)
        topics = topics_for_event(event)

        primary_art = linked_arts[0][0] if linked_arts else None
        primary_src = linked_arts[0][1] if linked_arts else None

        details_fa = summary.details_fa or {}
        primary_source_name = (
            details_fa.get("source")
            or (primary_src.name if primary_src else "منبع رسمی")
        )
        primary_url = (
            details_fa.get("url")
            or (primary_art.original_url if primary_art else "")
        )

        # Collect additional sources from Staleness Policy Option C: details_fa['sources']
        # The primary article is itself listed there, so it must not come back as
        # "parallel coverage": one outlet read twice is not corroboration.
        additional_sources: list[dict[str, Any]] = []
        if isinstance(details_fa.get("sources"), list):
            for s in details_fa["sources"]:
                if isinstance(s, dict) and s.get("url") != primary_url:
                    additional_sources.append({
                        "source": s.get("source", "منبع ناشناس"),
                        "url": s.get("url", ""),
                        "article_id": s.get("article_id"),
                        "added_at": s.get("added_at"),
                    })

        # Also add any linked articles not already in additional_sources or primary
        existing_urls = {primary_url} | {s["url"] for s in additional_sources if s.get("url")}
        for art, src in linked_arts[1:]:
            if art.original_url and art.original_url not in existing_urls:
                additional_sources.append({
                    "source": src.name if src else "منبع پیگیری",
                    "url": art.original_url,
                    "article_id": art.id,
                    "added_at": art.collected_at.isoformat() if art.collected_at else None,
                })
                existing_urls.add(art.original_url)

        cq = details_fa.get("content_quality")
        if not cq and primary_art:
            from app.editorial.content_quality import classify_content_quality

            cq = classify_content_quality(
                primary_art.title, primary_art.original_text, primary_art.text_source
            )
        cq_status = (cq or {}).get("status", "full_text")
        cq_label_fa = (cq or {}).get("label_fa", "متن کامل")
        cq_insufficient = (cq or {}).get("is_insufficient", False)

        is_digest = bool(details_fa.get("is_live_digest") or details_fa.get("article_kind") == "live_digest")

        item = {
            "event_id": event.id,
            "title": canonicalize_approved_names(event.title),
            "event_type": event.event_type or "GEN",
            "category_fa": CATEGORY_TITLES.get(event.event_type or "", "سایر تحولات"),
            "importance": event.importance,
            "first_seen_at": event.first_seen_at.isoformat() if event.first_seen_at else "",
            "countries": [canonicalize_approved_names(c) for c in (event.countries or [])],
            "actors": [canonicalize_approved_names(a) for a in (event.actors or [])],
            "location": event.location or "منطقه",
            "headline_fa": canonicalize_approved_names(summary.headline_fa),
            "summary_fa": canonicalize_approved_names(summary.summary_fa),
            "verification_status": summary.verification_status,
            "verification_status_fa": VERIFICATION_LABELS.get(
                summary.verification_status, "نامشخص"
            ),
            "content_quality": cq_status,
            "content_quality_fa": cq_label_fa,
            "is_insufficient": cq_insufficient,
            "is_live_digest": is_digest,
            # Phase T-2: per-camp claims, kept as stored so the same event reads the
            # same way in the Telegram bulletin and on the Telegraph page.
            "perspectives": [
                {
                    **p,
                    "claim_fa": canonicalize_approved_names(p.get("claim_fa", "")),
                }
                for p in details_fa.get("perspectives") or []
                if isinstance(p, dict)
            ],
            "disagreement_fa": canonicalize_approved_names(details_fa.get("disagreement_fa") or ""),
            "silent_parties_fa": [
                str(s).strip()
                for s in (details_fa.get("silent_parties_fa") or [])
                if str(s).strip()
            ],
            "primary_source": primary_source_name,
            "primary_url": primary_url,
            "has_media": any(getattr(art, "has_media", False) for art, _ in linked_arts),
            "additional_sources": additional_sources,
            "total_sources_count": max(1 + len(additional_sources), distinct_sources),
            "distinct_sources_count": distinct_sources,
            "topic_key": topic.key if topic else None,
            "topic_keys": [t.key for t in topics] if topics else ([topic.key] if topic else []),
            "topic_fa": topic.name_fa if topic else "سایر تحولات",
            "is_mock": is_mock,
            "language_warning": language_warning,
            "review_pending": event.id in flagged_ids,
        }

        if distinct_sources < 2:
            item["verification_status"] = _resolved_verification_status(
                item["verification_status"], distinct_sources
            )
            item["verification_status_fa"] = VERIFICATION_LABELS.get(
                item["verification_status"], "نامشخص"
            )

        # Regional filter: require Middle East country, city, or waterway in geography.
        # The completeness report is not regional: a world-news story collected in the
        # window must still appear.
        if (
            not include_all
            and getattr(settings, "bulletin_require_regional", True)
            and not has_regional_presence(item)
        ):
            logger.info("Excluding non-regional event ID %d ('%s') from bulletin.", event.id, event.title[:40])
            continue

        items.append(item)

    # Sort items: Importance DESC, Source count DESC, Recency DESC
    items.sort(key=_item_sort_key, reverse=True)

    # R-3: a bulletin is a briefing, not a dump; keep the strongest events only. The
    # completeness report is exempt: every collected story of the window is published.
    events_before_cap = len(items)
    max_items = max(0, settings.max_daily_report_items)
    if not include_all and max_items and len(items) > max_items:
        logger.info(
            "Capping the daily report at %d of %d eligible events.", max_items, events_before_cap
        )
        items = items[:max_items]

    if mock_count > 0 and real_count > 0:
        content_quality = "mixed"
    elif mock_count > 0:
        content_quality = "mock"
    elif real_count > 0:
        content_quality = "real"
    else:
        content_quality = "real"

    metadata = {
        "report_date": str(report_date),
        "generated_at": _utcnow().isoformat(),
        "min_importance": min_importance,
        "total_events": len(items),
        "strategic_events_count": len([i for i in items if i["importance"] >= 4]),
        "regional_events_count": len([i for i in items if i["importance"] < 4]),
        "content_quality": content_quality,
        "mock_summaries_count": mock_count,
        "real_summaries_count": real_count,
        "events_before_cap": events_before_cap,
        "max_items": max_items,
        "language_rejected_count": language_rejected_count,
        "min_created_at": (settings.daily_report_min_created_at or "").strip() or None,
        "completeness": "all_events" if include_all else "filtered",
        "flagged_events_included": flagged_events_included,
        "slot": slot_label(slot_hour) if slot_hour is not None else None,
        "timezone": settings.timezone,
    }

    return report_date, items, metadata


def esc(text: Any) -> str:
    """Escape text for Telegram HTML parse_mode."""
    if text is None:
        return ""
    return html.escape(str(text), quote=True)


def perspective_lines(item: dict[str, Any], as_html: bool = True) -> list[str]:
    """Render the narrative-comparison block of one item, or nothing when absent.

    Claims are grouped by editorial camp in display order, so the reader sees "غربی"
    next to "روسی" and "طرف درگیر" rather than one blended voice. A camp that stayed
    silent is named explicitly instead of being left out.
    """
    if item.get("is_live_digest"):
        return []

    grouped = group_perspectives(item.get("perspectives") or [])
    if not grouped:
        return []

    label = "   🗣 <b>مقایسه روایت‌ها:</b>" if as_html else "   🗣 مقایسه روایت‌ها:"
    lines: list[str] = [label]
    for orientation, claims in grouped:
        sources = "، ".join(
            dict.fromkeys(str(claim.get("source_name") or "").strip() for claim in claims)
        ).strip("، ")
        text = " / ".join(str(claim.get("claim_fa") or "").strip() for claim in claims)
        source_text = f" ({esc(sources)})" if sources else ""
        lines.append(f"      🔹 <b>{esc(orientation.label_fa)}</b>{source_text}: {esc(text)}" if as_html
                     else f"      🔹 {orientation.label_fa}{sources and f' ({sources})'}: {text}")

    disagreement = str(item.get("disagreement_fa") or "").strip()
    if disagreement:
        lines.append(f"      ⚠️ <b>نقاط اختلاف:</b> {esc(disagreement)}" if as_html
                     else f"      ⚠️ نقاط اختلاف: {disagreement}")

    if getattr(settings, "show_silent_parties", False):
        silent = [str(s).strip() for s in item.get("silent_parties_fa") or [] if str(s).strip()]
        if silent:
            joined = "، ".join(silent)
            lines.append(
                f"      🔇 <b>پوشش‌نشده در منابع پایش‌شده:</b> {esc(joined)}" if as_html
                else f"      🔇 پوشش‌نشده در منابع پایش‌شده: {joined}"
            )
    return lines


