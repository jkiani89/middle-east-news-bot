def _utcnow() -> datetime:
    return datetime.now(UTC)


def report_created_after_cutoff() -> datetime | None:
    """Earliest ``Event.created_at`` admitted into the bulletin (Phase R-5).

    Only events ingested after the language and verification guards went live are
    worth publishing; an empty ``daily_report_min_created_at`` disables the filter.
    """
    raw = (settings.daily_report_min_created_at or "").strip()
    if not raw:
        return None
    try:
        cutoff_date = date.fromisoformat(raw)
    except ValueError:
        logger.warning(
            "Invalid daily_report_min_created_at=%r; the created_at filter stays disabled.",
            raw,
        )
        return None
    return datetime.combine(cutoff_date, time.min, tzinfo=UTC)


def _resolved_verification_status(model_status: str, source_count: int) -> str:
    """Re-derive the verification label from corroboration at render time (R-1).

    ``app.processors.pipeline`` owns this rule but reaches this module through the
    Telegram publisher, so the import stays local to avoid a cycle.
    """
    from app.processors.pipeline import resolve_verification_status

    return resolve_verification_status(model_status, source_count)


def is_summary_mock(summary: Summary | Any) -> bool:
    """Detect whether a summary was generated by a mock provider or test placeholder."""
    model_name = getattr(summary, "model_name", "") or ""
    prompt_ver = getattr(summary, "prompt_version", "") or ""
    headline = getattr(summary, "headline_fa", "") or ""
    text = getattr(summary, "summary_fa", "") or ""

    if str(model_name).lower() in ("mock", "mockaiprovider", "test", "none"):
        return True
    if str(prompt_ver).lower() in ("mock", "test"):
        return True
    if headline.startswith("تیتر خبر") or text.startswith("خلاصه خبر"):
        return True
    if headline in ("رایزنی‌های دیپلماتیک منطقه‌ای", "Regional Diplomatic Activity"):
        return True
    return False


def report_slot_hours() -> tuple[int, ...]:
    """Configured briefing hours in local time, sorted and de-duplicated."""
    hours: list[int] = []
    for raw in (settings.report_slots or "").split(","):
        value = raw.strip()
        if value.isdigit() and 0 <= int(value) <= 23:
            hours.append(int(value))
    return tuple(sorted(set(hours))) or (settings.daily_report_hour,)


def slot_label(slot_hour: int) -> str:
    """Stable key for one briefing slot, e.g. ``"14:00"``."""
    return f"{slot_hour:02d}:00"


def current_slot_hour(now: datetime | None = None) -> int:
    """The briefing slot that is due now: the latest configured hour already passed."""
    tz = ZoneInfo(settings.timezone)
    moment = now or datetime.now(tz)
    slots = report_slot_hours()
    due = [hour for hour in slots if hour <= moment.hour]
    return due[-1] if due else slots[-1]


def report_window(
    report_date: date | None = None,
    slot_hour: int | None = None,
) -> tuple[date, datetime, datetime]:
    """Return (report_date, window_start, window_end).

    Without a slot this is the original 24-hour window anchored at the configured
    daily-report time, so repeated or delayed runs stay idempotent. With a slot it
    ends at that hour and starts at the previous slot, which keeps the three daily
    briefings gapless and free of overlap.
    """
    tz = ZoneInfo(settings.timezone)
    if report_date is None:
        report_date = datetime.now(tz).date()

    if slot_hour is None:
        end_hour = settings.daily_report_hour
        end_minute = settings.daily_report_minute
        window_hours = 24
    else:
        slots = report_slot_hours()
        earlier = [hour for hour in slots if hour < slot_hour]
        previous_hour = earlier[-1] if earlier else slots[-1]
        end_hour, end_minute = slot_hour, 0
        window_hours = (slot_hour - previous_hour) % 24 or 24

    window_end = datetime.combine(
        report_date,
        time(hour=end_hour, minute=end_minute),
        tzinfo=tz,
    )
    window_start = window_end - timedelta(hours=window_hours)
    return report_date, window_start, window_end


async def fetch_report_items(
    session: AsyncSession,
    report_date: date | None = None,
    min_importance: int | None = None,
    slot_hour: int | None = None,
) -> tuple[date, list[dict[str, Any]], dict[str, Any]]:
    """Query PostgreSQL for events in the 24-hour window matching report criteria.

    Strictly excludes any events containing articles with status 'flagged_for_review' or 'rejected'.
    Collects primary and supplementary source citations (Staleness Policy Option C).
    """
    if min_importance is None:
        min_importance = settings.min_importance

    report_date, window_start, window_end = report_window(report_date, slot_hour)

    # Subquery: identify events that have ANY article with flagged_for_review or rejected status
    flagged_subquery = (
        select(ArticleEvent.event_id)
        .join(Article, Article.id == ArticleEvent.article_id)
        .where(Article.status.in_(["flagged_for_review", "rejected"]))
    )

    conditions = [
        Event.first_seen_at >= window_start,
        Event.first_seen_at < window_end,
        Event.importance >= min_importance,
        Event.id.not_in(flagged_subquery),
    ]
    created_after = report_created_after_cutoff()
    if created_after is not None:
        # ``events`` has no created_at column (and adding one would need a migration);
        # first_seen_at is its ingestion timestamp, set once when the event is inserted.
        conditions.append(Event.first_seen_at >= created_after)

    # Query events in time window with importance threshold, excluding flagged
    stmt = (
        select(Event, Summary)
        .join(Summary, Summary.event_id == Event.id)
        .where(*conditions)
        .order_by(Event.importance.desc(), Event.first_seen_at.desc())
    )

    event_summary_rows = (await session.execute(stmt)).all()
    if not event_summary_rows:
        metadata = {
            "report_date": str(report_date),
            "generated_at": _utcnow().isoformat(),
            "min_importance": min_importance,
            "total_events": 0,
            "strategic_events_count": 0,
            "regional_events_count": 0,
            "events_before_cap": 0,
            "max_items": settings.max_daily_report_items,
            "language_rejected_count": 0,
            "min_created_at": (settings.daily_report_min_created_at or "").strip() or None,
        }
        return report_date, [], metadata

    event_ids = [ev.id for ev, _ in event_summary_rows]

    # Fetch all linked articles and their sources for these events
    articles_stmt = (
        select(ArticleEvent.event_id, Article, Source)
        .join(Article, Article.id == ArticleEvent.article_id)
        .join(Source, Source.id == Article.source_id)
        .where(ArticleEvent.event_id.in_(event_ids))
        .order_by(ArticleEvent.confidence.desc().nullslast(), Article.collected_at.asc())
    )
    article_rows = (await session.execute(articles_stmt)).all()

    # Group articles by event_id
    articles_by_event: dict[int, list[tuple[Article, Source]]] = {eid: [] for eid in event_ids}
    for eid, art, src in article_rows:
        articles_by_event[eid].append((art, src))

    items: list[dict[str, Any]] = []
    seen_event_ids: set[int] = set()
    mock_count = 0
    real_count = 0
    language_rejected_count = 0

    for event, summary in event_summary_rows:
        if event.id in seen_event_ids:
            continue
        seen_event_ids.add(event.id)

        # R-1: stored text may predate the Phase N guard, so re-check it here and
        # drop anything that is not fluent Persian instead of spreading it further.
        if not (
            passes_persian_guard(summary.headline_fa)
            and passes_persian_guard(summary.summary_fa)
        ):
            language_rejected_count += 1
            logger.warning(
                "Event #%d dropped from the daily report: headline/summary failed the Persian language guard.",
                event.id,
            )
            continue

        is_mock = is_summary_mock(summary)
        if is_mock:
            mock_count += 1
        else:
            real_count += 1

        linked_arts = articles_by_event.get(event.id, [])

        # R-1: independent sources are recounted from the linked articles at render
        # time, so a stale stored verdict can never present a single source as confirmed.
        distinct_sources = len(
            {
                art.source_id
                for art, _src in linked_arts
                if getattr(art, "source_id", None) is not None
            }
        )

        topic = topic_for_event(event)

        primary_art = linked_arts[0][0] if linked_arts else None
        primary_src = linked_arts[0][1] if linked_arts else None

        details_fa = summary.details_fa or {}
        primary_source_name = (
            details_fa.get("source")
            or (primary_src.name if primary_src else "منبع رسمی")
        )
        primary_url = (
            details_fa.get("url")
            or (primary_art.original_url if primary_art else "")
        )

        # Collect additional sources from Staleness Policy Option C: details_fa['sources']
        additional_sources: list[dict[str, Any]] = []
        if isinstance(details_fa.get("sources"), list):
            for s in details_fa["sources"]:
                if isinstance(s, dict):
                    additional_sources.append({
                        "source": s.get("source", "منبع ناشناس"),
                        "url": s.get("url", ""),
                        "article_id": s.get("article_id"),
                        "added_at": s.get("added_at"),
                    })

        # Also add any linked articles not already in additional_sources or primary
        existing_urls = {primary_url} | {s["url"] for s in additional_sources if s.get("url")}
        for art, src in linked_arts[1:]:
            if art.original_url and art.original_url not in existing_urls:
                additional_sources.append({
                    "source": src.name if src else "منبع پیگیری",
                    "url": art.original_url,
                    "article_id": art.id,
                    "added_at": art.collected_at.isoformat() if art.collected_at else None,
                })
                existing_urls.add(art.original_url)

        item = {
            "event_id": event.id,
            "title": event.title,
            "event_type": event.event_type or "GEN",
            "category_fa": CATEGORY_TITLES.get(event.event_type or "", "سایر تحولات"),
            "importance": event.importance,
            "first_seen_at": event.first_seen_at.isoformat() if event.first_seen_at else "",
            "countries": event.countries or [],
            "actors": event.actors or [],
            "location": event.location or "منطقه",
            "headline_fa": summary.headline_fa,
            "summary_fa": summary.summary_fa,
            "verification_status": summary.verification_status,
            "verification_status_fa": VERIFICATION_LABELS.get(
                summary.verification_status, "نامشخص"
            ),
            "primary_source": primary_source_name,
            "primary_url": primary_url,
            "additional_sources": additional_sources,
            "total_sources_count": max(1 + len(additional_sources), distinct_sources),
            "distinct_sources_count": distinct_sources,
            "topic_key": topic.key if topic else None,
            "topic_fa": topic.name_fa if topic else "سایر تحولات",
            "is_mock": is_mock,
        }

        if distinct_sources < 2:
            item["verification_status"] = _resolved_verification_status(
                item["verification_status"], distinct_sources
            )
            item["verification_status_fa"] = VERIFICATION_LABELS.get(
                item["verification_status"], "نامشخص"
            )

        items.append(item)

    # R-3: a bulletin is a briefing, not a dump; keep the strongest events only.
    events_before_cap = len(items)
    max_items = max(0, settings.max_daily_report_items)
    if max_items and len(items) > max_items:
        logger.info(
            "Capping the daily report at %d of %d eligible events.", max_items, events_before_cap
        )
        items = items[:max_items]

    if mock_count > 0 and real_count > 0:
        content_quality = "mixed"
    elif mock_count > 0:
        content_quality = "mock"
    elif real_count > 0:
        content_quality = "real"
    else:
        content_quality = "real"

    metadata = {
        "report_date": str(report_date),
        "generated_at": _utcnow().isoformat(),
        "min_importance": min_importance,
        "total_events": len(items),
        "strategic_events_count": len([i for i in items if i["importance"] >= 4]),
        "regional_events_count": len([i for i in items if i["importance"] < 4]),
        "content_quality": content_quality,
        "mock_summaries_count": mock_count,
        "real_summaries_count": real_count,
        "events_before_cap": events_before_cap,
        "max_items": max_items,
        "language_rejected_count": language_rejected_count,
        "min_created_at": (settings.daily_report_min_created_at or "").strip() or None,
        "slot": slot_label(slot_hour) if slot_hour is not None else None,
        "timezone": settings.timezone,
    }

    return report_date, items, metadata


def esc(text: Any) -> str:
    """Escape text for Telegram HTML parse_mode."""
    if text is None:
        return ""
    return html.escape(str(text), quote=True)


def format_persian_daily_report(
    report_date: date,
    items: list[dict[str, Any]],
    metadata: dict[str, Any] | None = None,
    as_html: bool = True,
    include_header: bool = True,
    include_footer: bool = True,
    section_titles: tuple[str, str] | None = None,
) -> str:
    """Format structured items into a clean, professional Persian daily intelligence report.

    Adheres strictly to EDITORIAL_POLICY.md guidelines:
    - Neutral tone, zero speculation
    - Claim attribution to primary and secondary sources
    - Distinct sections for strategic and regional developments
    - Explicit listing of supplementary sources (Staleness Policy Option C)
    - Supports HTML parse_mode with <b>, <code>, and <a> links (Option B)
    """
    if metadata is None:
        metadata = {
            "report_date": str(report_date),
            "total_events": len(items),
            "strategic_events_count": len([i for i in items if i.get("importance", 3) >= 4]),
            "regional_events_count": len([i for i in items if i.get("importance", 3) < 4]),
            "min_importance": settings.min_importance,
        }

    total_events = metadata.get("total_events", len(items))
    strategic_count = metadata.get("strategic_events_count", 0)
    regional_count = metadata.get("regional_events_count", 0)
    min_imp = metadata.get("min_importance", settings.min_importance)
    content_quality = metadata.get("content_quality", "real")

    if content_quality == "mock":
        quality_badge = "⚠️ کیفیت محتوا: شبیه‌سازی / آزمایشی (غیرقابل انتشار عمومی در تلگرام)"
    elif content_quality == "mixed":
        quality_badge = "⚠️ کیفیت محتوا: ترکیبی (نیازمند بازپردازش کامل قبل از انتشار)"
    else:
        quality_badge = "✅ کیفیت محتوا: تحلیل رسمی هوش مصنوعی (آماده انتشار)"

    lines: list[str] = []
    if include_header and as_html:
        lines = [
            "<b>📊 بولتن هوش و پایش تحولات خاورمیانه و جهان اسلام</b>",
            f"📅 تاریخ گزارش: <code>{report_date.strftime('%Y/%m/%d') if hasattr(report_date, 'strftime') else str(report_date)}</code> (بازه پایش ۲۴ ساعته)",
            f"📈 آمار رویدادها: <b>{total_events}</b> رخداد واجد شرایط (اهمیت ≥ {min_imp}) | "
            f"راهبردی: <b>{strategic_count}</b> | منطقه‌ای: <b>{regional_count}</b>",
            quality_badge,
            "═" * 50,
            "",
        ]
    elif include_header:
        lines = [
            "📊 بولتن هوش و پایش تحولات خاورمیانه و جهان اسلام",
            f"📅 تاریخ گزارش: {report_date.strftime('%Y/%m/%d') if hasattr(report_date, 'strftime') else str(report_date)} (بازه پایش ۲۴ ساعته)",
            f"📈 آمار رویدادها: {total_events} رخداد واجد شرایط (اهمیت ≥ {min_imp}) | "
            f"راهبردی: {strategic_count} | منطقه‌ای: {regional_count}",
            quality_badge,
            "═" * 50,
            "",
        ]

    strategic_items = [i for i in items if i.get("importance", 3) >= 4]
    regional_items = [i for i in items if i.get("importance", 3) < 4]

    # Section 1: Strategic Developments (Importance >= 4)
    if strategic_items:
        strategic_title = (
            section_titles[0] if section_titles else "🔴 بخش اول: اهم تحولات راهبردی (اولویت بالا)"
        )
        sec1_header = f"<b>{esc(strategic_title)}</b>" if as_html else strategic_title
        lines.extend([
            sec1_header,
            "─" * 45,
        ])
        for idx, item in enumerate(strategic_items, start=1):
            importance = item.get("importance", 4)
            stars = "⭐" * importance
            cat = item.get("category_fa", "عمومی")
            event_type = item.get("event_type", "GEN")
            headline = item.get("headline_fa") or item.get("headline", "")
            summary_txt = item.get("summary_fa") or item.get("summary", "")
            verification = item.get("verification_status_fa") or item.get("verification_status", "تأییدشده")
            primary_src = item.get("primary_source") or item.get("source", "منبع رسمی")
            primary_u = item.get("primary_url") or item.get("url", "")

            geo = ", ".join(item.get("countries", [])) or item.get("location", "منطقه")
            acts = ", ".join(item.get("actors", [])) or "نهادهای رسمی"

            if as_html:
                lines.append(f"{idx}. 📌 <b>{esc(headline)}</b>")
                lines.append(f"   ▫️ درجه اهمیت: {stars} ({importance}/5) | حوزه: <b>{esc(cat)}</b> [{esc(event_type)}]")
                lines.append(f"   ▫️ جغرافیا و بازیگران: {esc(geo)} | {esc(acts)}")
                lines.append(f"   ▫️ خلاصه گزیده: {esc(summary_txt)}")
                lines.append(f"   ▫️ راستی‌آزمایی: {esc(verification)}")
                if primary_u:
                    lines.append(f"   ▫️ منبع اصلی: <a href=\"{esc(primary_u)}\">{esc(primary_src)}</a>")
                else:
                    lines.append(f"   ▫️ منبع اصلی: {esc(primary_src)}")

                # Supplementary sources from EventMatcher / Staleness Policy C
                if item.get("additional_sources"):
                    lines.append("   🔗 پوشش‌های موازی و منابع تکمیلی:")
                    for supp in item["additional_sources"]:
                        supp_src = esc(supp.get("source", "منبع پیگیری"))
                        supp_url = supp.get("url", "")
                        if supp_url:
                            lines.append(f"      • <a href=\"{esc(supp_url)}\">{supp_src}</a>")
                        else:
                            lines.append(f"      • {supp_src}")
            else:
                lines.append(f"{idx}. 📌 {headline}")
                lines.append(f"   ▫️ درجه اهمیت: {stars} ({importance}/5) | حوزه: {cat} [{event_type}]")
                lines.append(f"   ▫️ جغرافیا و بازیگران: {geo} | {acts}")
                lines.append(f"   ▫️ خلاصه گزیده: {summary_txt}")
                lines.append(f"   ▫️ راستی‌آزمایی: {verification}")
                lines.append(f"   ▫️ منبع اصلی: {primary_src} ⟵ {primary_u}")
                if item.get("additional_sources"):
                    lines.append("   🔗 پوشش‌های موازی و منابع تکمیلی:")
                    for supp in item["additional_sources"]:
                        supp_src = supp.get("source", "منبع پیگیری")
                        supp_url = supp.get("url", "")
                        lines.append(f"      • {supp_src}: {supp_url}")
            lines.append("")

    # Section 2: Regional & Thematic Developments (Importance 2 & 3)
    if regional_items:
        regional_title = (
            section_titles[1] if section_titles else "🌐 بخش دوم: سایر تحولات منطقه‌ای و موضوعی"
        )
        sec2_header = f"<b>{esc(regional_title)}</b>" if as_html else regional_title
        lines.extend([
            sec2_header,
            "─" * 45,
        ])
        # Group by category
        by_category: dict[str, list[dict[str, Any]]] = {}
        for item in regional_items:
            cat_name = item.get("category_fa", "عمومی")
            by_category.setdefault(cat_name, []).append(item)

        for cat_name, cat_items in by_category.items():
            if as_html:
                lines.append(f"🔹 <b>{esc(cat_name)}:</b>")
            else:
                lines.append(f"🔹 {cat_name}:")

            for item in cat_items:
                importance = item.get("importance", 3)
                stars = "⭐" * importance
                headline = item.get("headline_fa") or item.get("headline", "")
                summary_txt = item.get("summary_fa") or item.get("summary", "")
                verification = item.get("verification_status_fa") or item.get("verification_status", "تأییدشده")
                primary_src = item.get("primary_source") or item.get("source", "منبع")
                primary_u = item.get("primary_url") or item.get("url", "")

                if as_html:
                    lines.append(f"  • <b>{esc(headline)}</b> ({stars})")
                    lines.append(f"    - خلاصه: {esc(summary_txt)}")
                    if primary_u:
                        lines.append(f"    - راستی‌آزمایی: {esc(verification)} | منبع: <a href=\"{esc(primary_u)}\">{esc(primary_src)}</a>")
                    else:
                        lines.append(f"    - راستی‌آزمایی: {esc(verification)} | منبع: {esc(primary_src)}")
                    if item.get("additional_sources"):
                        lines.append("    - منابع موازی:")
                        for supp in item["additional_sources"]:
                            supp_src = esc(supp.get("source", "منبع"))
                            supp_url = supp.get("url", "")
                            if supp_url:
                                lines.append(f"      * <a href=\"{esc(supp_url)}\">{supp_src}</a>")
                            else:
                                lines.append(f"      * {supp_src}")
                else:
                    lines.append(f"  • {headline} ({stars})")
                    lines.append(f"    - خلاصه: {summary_txt}")
                    lines.append(f"    - راستی‌آزمایی: {verification} | منبع: {primary_src}")
                    if primary_u:
                        lines.append(f"    - پیوند: {primary_u}")
                    if item.get("additional_sources"):
                        lines.append("    - منابع موازی:")
                        for supp in item["additional_sources"]:
                            lines.append(f"      * {supp.get('source')}: {supp.get('url')}")
            lines.append("")

    if not items:
        lines.append("در بازه ۲۴ ساعته گذشته هیچ رویدادی با شرایط مدنظر ثبت نگردیده است.")
        lines.append("")

    # Footer: Editorial Disclosure
    if include_footer:
        footer_header = "<b>🛡 یادداشت صحت اطلاعات و خط‌مشی تحریریه (Editorial Note):</b>" if as_html else "🛡 یادداشت صحت اطلاعات و خط‌مشی تحریریه (Editorial Note):"
        lines.extend([
            "═" * 50,
            footer_header,
            "این گزارش به صورت کاملاً خودکار بر مبنای اصول بی‌طرفی، انتساب دقیق مواضع رسمی",
            "و تجمیع رویدادهای مستقل تدوین شده است. هیچ‌گونه قضاوت سیاسی، فرضیه‌سازی",
            "یا توهم زبانی در تهیه این بولتن وارد نشده است.",
        ])

    return "\n".join(lines)


async def build_daily_report(
    report_date: date | None = None,
    min_importance: int | None = None,
    session: AsyncSession | None = None,
) -> tuple[date, list[dict[str, Any]]]:
    """Generate daily report items, format report text, and save/update DailyReport record.

    Backward-compatible signature: returns (report_date, items).
    """
    if session is not None:
        return await _build_daily_report_with_session(session, report_date, min_importance)

    async with SessionLocal() as db_session:
        res = await _build_daily_report_with_session(db_session, report_date, min_importance)
        await db_session.commit()
        return res


async def _build_daily_report_with_session(
    session: AsyncSession,
    report_date: date | None = None,
    min_importance: int | None = None,
) -> tuple[date, list[dict[str, Any]]]:
    rep_date, items, metadata = await fetch_report_items(
        session, report_date=report_date, min_importance=min_importance
    )
    formatted_text = format_persian_daily_report(rep_date, items, metadata)

    report = await session.scalar(
        select(DailyReport).where(DailyReport.report_date == rep_date)
    )

    payload = {
        "date": str(rep_date),
        "content_quality": metadata.get("content_quality", "real"),
        "metadata": metadata,
        "formatted_text": formatted_text,
        "items": items,
    }

    if report:
        report.content = payload
        report.status = "generated"
        report.generated_at = _utcnow()
        report.telegram_message_ids = []
        report.published_at = None
    else:
        report = DailyReport(
            report_date=rep_date,
            content=payload,
            status="generated",
            generated_at=_utcnow(),
        )
        session.add(report)

    logger.info(
        "Daily report generated for %s: %d items (strategic: %d, regional: %d)",
        rep_date,
        len(items),
        metadata.get("strategic_events_count", 0),
        metadata.get("regional_events_count", 0),
    )
    return rep_date, items


def group_items_by_topic(
    items: list[dict[str, Any]],
) -> list[tuple[str, str, list[dict[str, Any]]]]:
    """Group items into briefing sections, in configured topic priority order."""
    names: dict[str, str] = {topic.key: topic.name_fa for topic in load_topics()}
    grouped: dict[str, list[dict[str, Any]]] = {key: [] for key in names}
    for item in items:
        key = item.get("topic_key") or "other"
        if key not in names:
            names[key] = item.get("topic_fa") or "سایر تحولات"
            grouped.setdefault(key, [])
        grouped[key].append(item)
    return [(key, names[key], grouped[key]) for key in names if grouped.get(key)]


def format_slot_bulletin(
    report_date: date,
    sections: list[tuple[str, str, list[dict[str, Any]]]],
    slot_hour: int,
    metadata: dict[str, Any] | None = None,
    as_html: bool = True,
) -> str:
    """Render one scheduled briefing: a header plus one section per topic."""
    metadata = metadata or {}
    total = sum(len(topic_items) for _key, _name, topic_items in sections)
    min_imp = metadata.get("min_importance", settings.min_importance)
    quality = metadata.get("content_quality", "real")

    if quality == "mock":
        badge = "⚠️ کیفیت محتوا: شبیه‌سازی / آزمایشی (غیرقابل انتشار عمومی)"
    elif quality == "mixed":
        badge = "⚠️ کیفیت محتوا: ترکیبی (نیازمند بازپردازش پیش از انتشار)"
    else:
        badge = "✅ کیفیت محتوا: تحلیل رسمی هوش مصنوعی (آماده انتشار)"

    date_text = report_date.strftime("%Y/%m/%d") if hasattr(report_date, "strftime") else str(report_date)
    title = "📊 بولتن زمان‌بندی‌شده تحولات منطقه و جهان"
    subtitle = f"📅 تاریخ: {date_text} | نوبت: {slot_label(slot_hour)}"
    stats = f"📈 {total} رویداد در {len(sections)} بخش (اهمیت ≥ {min_imp})"

    if as_html:
        lines = [
            f"<b>{esc(title)}</b>",
            esc(subtitle),
            esc(stats),
            badge,
            "═" * 50,
            "",
        ]
    else:
        lines = [title, subtitle, stats, badge, "═" * 50, ""]

    for _key, name, topic_items in sections:
        lines.append(
            format_persian_daily_report(
                report_date,
                topic_items,
                {"total_events": len(topic_items), "min_importance": min_imp},
                as_html=as_html,
                include_header=False,
                include_footer=False,
                section_titles=(f"🔴 {name} — تحولات راهبردی", f"🌐 {name} — سایر تحولات"),
            )
        )

    if not sections:
        lines.append("در این بازه هیچ رویدادی واجد شرایط انتشار نبود.")
        lines.append("")

    if as_html:
        lines.extend(["═" * 50, "<b>🛡 یادداشت تحریریه:</b>"])
    else:
        lines.extend(["═" * 50, "🛡 یادداشت تحریریه:"])
    lines.append("این بولتن به‌صورت خودکار و بر پایه اصول بی‌طرفی و انتساب دقیق منابع تدوین شده است.")
    return "\n".join(lines)


async def generate_slot_bulletins(
    report_date: date | None = None,
    slot_hour: int | None = None,
    min_importance: int | None = None,
) -> tuple[date, list[tuple[str, str, list[dict[str, Any]]]], str, dict[str, Any]]:
    """Build one scheduled briefing and store it under ``content['bulletins'][slot]``.

    The window of a slot starts where the previous slot ended, so the three daily
    briefings neither overlap nor leave a gap. Delivery state lives in the nested
    record, which keeps the single-row-per-date ``daily_reports`` schema intact.
    """
    if slot_hour is None:
        slot_hour = current_slot_hour()

    async with SessionLocal() as session:
        rep_date, items, metadata = await fetch_report_items(
            session,
            report_date=report_date,
            min_importance=min_importance,
            slot_hour=slot_hour,
        )
        sections = group_items_by_topic(items)
        formatted_text = format_slot_bulletin(rep_date, sections, slot_hour, metadata)
        label = slot_label(slot_hour)

        report = await session.scalar(
            select(DailyReport).where(DailyReport.report_date == rep_date)
        )
        content: dict[str, Any] = dict(report.content or {}) if report else {}
        bulletins: dict[str, Any] = dict(content.get("bulletins") or {})
        previous: dict[str, Any] = dict(bulletins.get(label) or {})

        payload: dict[str, Any] = {
            "slot": label,
            "date": str(rep_date),
            "content_quality": metadata.get("content_quality", "real"),
            "metadata": metadata,
            "formatted_text": formatted_text,
            "items": items,
            "sections": [
                {"topic_key": key, "topic_fa": name, "count": len(topic_items)}
                for key, name, topic_items in sections
            ],
            "message_ids": previous.get("message_ids") or [],
            "pdf_message_id": previous.get("pdf_message_id"),
            "status": "generated",
        }
        bulletins[label] = payload

        new_content = {
            **content,
            "date": str(rep_date),
            "content_quality": payload["content_quality"],
            "metadata": metadata,
            "formatted_text": formatted_text,
            "items": items,
            "bulletins": bulletins,
        }

        if report:
            report.content = new_content
            report.status = "generated"
            report.generated_at = _utcnow()
        else:
            report = DailyReport(
                report_date=rep_date,
                content=new_content,
                status="generated",
                generated_at=_utcnow(),
            )
            session.add(report)
        await session.commit()

    logger.info(
        "Briefing %s for %s generated: %d events in %d section(s).",
        label,
        rep_date,
        len(items),
        len(sections),
    )
    return rep_date, sections, formatted_text, metadata


async def mark_slot_published(
    session: AsyncSession,
    report_date: date,
    slot_hour: int,
    message_ids: list[int],
    pdf_message_id: int | None = None,
) -> None:
    """Record delivery of one briefing slot so a re-run never reposts it."""
    report = await session.scalar(
        select(DailyReport).where(DailyReport.report_date == report_date)
    )
    if report is None:
        return
    content: dict[str, Any] = dict(report.content or {})
    bulletins: dict[str, Any] = dict(content.get("bulletins") or {})
    label = slot_label(slot_hour)
    payload: dict[str, Any] = dict(bulletins.get(label) or {})
    payload["status"] = "published"
    payload["message_ids"] = message_ids
    payload["pdf_message_id"] = pdf_message_id
    bulletins[label] = payload
    content["bulletins"] = bulletins
    report.content = content
    report.telegram_message_ids = message_ids
    report.published_at = _utcnow()
    report.status = "published" if all(
        (slot.get("status") == "published") for slot in bulletins.values()
    ) else "generated"
    await session.commit()


